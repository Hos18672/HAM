fun words(lang: String) = if (lang == "fa") FA else DE

/** Persian digits in Persian, Latin ones in German. */
fun digits(text: String, lang: String): String {
    if (lang != "fa") return text
    val out = StringBuilder(text.length)
    for (c in text) out.append(if (c in '0'..'9') '۰' + (c - '0') else c)
    return out.toString()
}

fun digits(n: Int, lang: String) = digits(n.toString(), lang)
